/** 查询简码对应的表情；大小写不敏感，未收录时返回 null。 */
export function emojiFor(name: string): string | null {
  return EMOJI_MAP[name.toLowerCase()] ?? null
}

/** 表情选择器条目：保留首个简码，按表情去重。 */
export interface EmojiChoice {
  name: string
  emoji: string
}

/** 选择器使用的表情清单；同一表情的多个简码只保留最先定义的一个。 */
export const EMOJI_CHOICES: EmojiChoice[] = (() => {
  const seen = new Set<string>()
  const choices: EmojiChoice[] = []
  for (const [name, emoji] of Object.entries(EMOJI_MAP)) {
    if (seen.has(emoji)) continue
    seen.add(emoji)
    choices.push({ name, emoji })
  }
  return choices
})()
